def default_question(ch, slot: int):
    term, desc = ch['definitions'][min(slot - 1, len(ch['definitions']) - 1)]
    label, rule = ch['rules'][min(slot - 1, len(ch['rules']) - 1)]
    if slot == 1:
        return {'question':f'「{term}」在本章最精確的意義為何？','answer':desc,'explanation':f'本章先用正式定義固定用語：「{term}」是指 {desc}'}
    if slot == 2:
        return {'question':f'關於「{label}」，作答案時最應掌握的規則是什麼？','answer':rule,'explanation':f'這是本章的核心規則：{rule}'}
    if slot == 3:
        return {'question':f'案例題進入「{ch["title"]}」時，最穩健的第一個分類步驟是什麼？','answer':ch['exam'][0],'explanation':'先分類再套條文，比直接背結論更能避免把不同法律效果混在一起。'+ch['intuition'][0]}
    if slot == 4:
        return {'question':f'綜合題若依「{ch["figure"][0]}」處理，應如何避免漏寫要件？','answer':'依圖示順序逐一確認主體、法律關係、成立要件、例外或抗辯，再寫法律效果。','explanation':'圖解是整理順序，不取代條文要件；最後仍要回到本章核心規則與題目事實。'}
    trap = ch['traps'][0]
    return {'question':f'陷阱判斷：「{trap}」是否正確？','answer':'不正確。','explanation':f'本章把它列為常見錯誤。正確作法是：{ch["exam"][0]}，並依具體法定要件判斷。'}


def build_questions():
    items=[]
    for ch in CHAPTERS:
        for slot in range(1,6):
            qid=f'{ch["id"]}-q{slot:02d}'
            item={'id':qid,'chapterId':ch['id'],**default_question(ch,slot)}
            if qid in SPECIAL:
                item.update(SPECIAL[qid])
            items.append(item)
    assert len(items)==100
    assert len({x['id'] for x in items})==100
    return items
